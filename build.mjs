// Builds the separate pages (/harshana, /brands, /production, /work/<project>)
// from index.html, so each one has its own URL, title and share preview.
// index.html is the only file to edit by hand. After editing it, run:  node build.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";

const SITE = "https://sihakuru.com";
const src = readFileSync("index.html", "utf8");

// Read the project list straight from the page's own script
const m = src.match(/const cases=(\[[\s\S]*?\]);\n/);
if (!m) throw new Error("Couldn't find `const cases=[...]` in index.html");
const cases = new Function(`return ${m[1]}`)();

const esc = (t) => String(t).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const strip = (t) => String(t).replace(/<[^>]*>/g, "");
const clip = (t, n = 160) => (t.length > n ? t.slice(0, n - 1).replace(/\s+\S*$/, "") + "…" : t);

const pages = [
  {
    file: "harshana.html", path: "/harshana", view: "founder",
    title: "Harshana Rajapaksha · Founder & CEO, Sihakuru",
    desc: "Creative designer, filmmaker and visual storyteller. Founder & CEO of Sihakuru, a branding and content studio in Sri Lanka.",
  },
  {
    file: "brands.html", path: "/brands", view: "brands",
    title: "Brand identities · Sihakuru",
    desc: "Logos and brand identities Sihakuru has designed for restaurants, villas, salons, wellness and food brands in Sri Lanka.",
  },
  {
    file: "production.html", path: "/production", view: "production",
    title: "Production & social · Sihakuru Labs",
    desc: "Commercials, hotel shoots, reels and social media work by Sihakuru Labs, with the story behind each project.",
  },
  ...cases.map((c) => ({
    file: `work/${c.s}.html`, path: `/work/${c.s}`, view: "case",
    title: `${strip(c.n)} · Sihakuru`,
    desc: clip(strip(c.p || `${c.n}: ${c.t} by Sihakuru Labs.`)),
    image: c.img,
  })),
];

const set = (html, re, val, label) => {
  if (!(typeof re === "string" ? html.includes(re) : re.test(html))) throw new Error(`Missing ${label} in index.html`);
  return html.replace(re, val);
};

for (const pg of pages) {
  const url = SITE + pg.path, t = esc(pg.title), d = esc(pg.desc);
  let h = src;
  h = set(h, /<title>[^<]*<\/title>/, `<title>${t}</title>`, "title");
  h = set(h, /(<meta name="description" content=")[^"]*/, `$1${d}`, "description");
  h = set(h, /(<link rel="canonical" href=")[^"]*/, `$1${url}`, "canonical");
  h = set(h, /(<meta property="og:title" content=")[^"]*/, `$1${t}`, "og:title");
  h = set(h, /(<meta property="og:description" content=")[^"]*/, `$1${d}`, "og:description");
  h = set(h, /(<meta property="og:url" content=")[^"]*/, `$1${url}`, "og:url");
  h = h.replace(/(<meta name="twitter:title" content=")[^"]*/, `$1${t}`);
  h = h.replace(/(<meta name="twitter:description" content=")[^"]*/, `$1${d}`);
  if (pg.image) {
    const img = SITE + pg.image;
    h = h.replace(/(<meta property="og:image" content=")[^"]*/, `$1${img}`);
    h = h.replace(/(<meta name="twitter:image" content=")[^"]*/, `$1${img}`);
    h = h.replace(/<meta property="og:image:width"[^>]*>\n?<meta property="og:image:height"[^>]*>\n?/, "");
  }
  // Show the right section straight away, before the script runs
  h = set(h, '<main id="home" class="view on">', '<main id="home" class="view">', "home view");
  h = set(h, `<main id="${pg.view}" class="view">`, `<main id="${pg.view}" class="view on">`, `${pg.view} view`);
  h = h.replace("<html", "<!-- Generated by build.mjs from index.html. Edit index.html, then run: node build.mjs -->\n<html");

  if (pg.file.includes("/")) mkdirSync(pg.file.split("/").slice(0, -1).join("/"), { recursive: true });
  writeFileSync(pg.file, h);
}

// The old founder copy lived in harshana/index.html; harshana.html replaces it
if (existsSync("harshana/index.html")) rmSync("harshana", { recursive: true });

const today = new Date().toISOString().slice(0, 10);
const urls = ["/", ...pages.map((p) => p.path)];
writeFileSync(
  "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map((u) => `  <url><loc>${SITE}${u === "/" ? "/" : u}</loc><lastmod>${today}</lastmod></url>`).join("\n") +
    `\n</urlset>\n`
);

console.log(`Built ${pages.length} pages:\n` + pages.map((p) => `  ${p.path}  ->  ${p.file}`).join("\n"));
